/*
 Flowable 表名大小写修复脚本（完整版）

 问题：Linux MySQL lower_case_table_names=0 下，Flowable 查 ACT_XXX 而实际为 act_xxx，导致失败

 解决：先删除可能存在的空大写表，再将所有 act_* 小写表重命名为 ACT_* 大写（保留数据）

 覆盖表：ACT_EVT_LOG, ACT_GE_*, ACT_HI_*, ACT_ID_*, ACT_PROCDEF_INFO, ACT_RE_*, ACT_RU_*

 注意：必须用 -f 执行，部分表可能不存在会报错，-f 会继续执行其他语句

 用法：docker exec -i mysql mysql -f -u root -pTH0901th ruoyi-vue-pro < flowable-fix-table-case.sql
*/

