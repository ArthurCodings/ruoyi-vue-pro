DROP TABLE IF EXISTS `ACT_RU_TASK`;
DROP TABLE IF EXISTS `ACT_RU_TIMER_JOB`;
DROP TABLE IF EXISTS `ACT_RU_VARIABLE`;

-- ========== 第二步：将小写表重命名为大写（保留数据） ==========
